"""
Builds the appendix table of the item screening (step 00): every item excluded from the 65-item
three-factor EFA solution, and the items retained after the missing-data review, with the rule applied.

Inputs (made by screen-efa-items.py and review-missing-data.py):
  output/efa-screening-items.csv     loadings, decision and reason
  output/missing-data-review.csv     missing % overall and per system, rule criteria
  input/missing-data-review-notes.csv  short description of the content of the reviewed items
  ../data/codebook/items.csv         item wording

Output:
  output/table-screening-decisions.tex   LaTeX table (table*), label tab:screening-decisions

Run from the repository root (after the two scripts above):
  python phase2-2-item-reduction/00-efa-screening/build-screening-table.py
"""
from pathlib import Path

import pandas as pd

STEP = Path(__file__).resolve().parent
PHASE = STEP.parent
FACTOR = {"task_cognition": "Task", "system": "Sys", "visualization": "Vis"}
CROSS_CUT, WEAK, SYSTEM_MAX = 0.32, 0.40, 3.0


def esc(t):
    return str(t).replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")


def main():
    scr = pd.read_csv(STEP / "output" / "efa-screening-items.csv").set_index("code")
    rev = pd.read_csv(STEP / "output" / "missing-data-review.csv").set_index("code")
    notes = pd.read_csv(STEP / "input" / "missing-data-review-notes.csv").set_index("code")
    wording = pd.read_csv(PHASE / "data" / "codebook" / "items.csv").set_index("code")["wording"]

    def row(code, rule):
        s, r = scr.loc[code], rev.loc[code]
        miss = (f"{r.missing_pct_all:.1f} / {r.max_system_pct:.1f} ({r.max_system})" if r.max_system_pct > 0
                else "0.0 / 0.0")
        return (f"{code} & {esc(wording[code])} & {FACTOR[s.factor]} & {s.primary_loading:.2f} & "
                f"{s.second_loading:.2f} ({FACTOR[s.second_factor]}) & {miss} & {rule} \\\\")

    def missing_rule(code):
        r, c = rev.loc[code], notes.loc[code, "content"] if code in notes.index else ""
        parts = []
        if isinstance(r.rule_criteria, str) and r.rule_criteria:
            for crit in r.rule_criteria.split("; "):
                if crit.startswith("1"):
                    parts.append(f"(1) weak loading")
                elif crit.startswith("2"):
                    parts.append("(2) " + crit[2:].replace("redundant", "redundant").strip())
                elif crit.startswith("3"):
                    parts.append(f"(3) feature/data-specific: {c}")
            return "; ".join(parts)
        return f"none: general aspect ({c})"

    cross = scr[scr.reason.fillna("").str.startswith("cross-loading")].sort_values(["factor", "second_loading"], ascending=[True, False])
    miss_ex = scr[scr.reason.fillna("").str.startswith("missing")]
    miss_ex = miss_ex.loc[rev.loc[miss_ex.index].sort_values("max_system_pct", ascending=False).index]
    kept = rev[(rev.rule_matches == "yes") & (rev.decision == "retained")].sort_values("max_system_pct", ascending=False)

    head = ("Code & Item & Factor & $\\lambda$ & 2nd $\\lambda$ & Missing \\% & Rule \\\\\n"
            " & & & & & (all / max) & \\\\")
    T = ["% Generated by phase2-2-item-reduction/00-efa-screening/build-screening-table.py -- do not edit by hand",
         "% table* spans both columns of a two-column layout; needs \\usepackage{array}",
         "\\begin{table*}[htbp]", "\\centering", "\\footnotesize",
         f"\\caption{{Item screening from the 65 items of the three-factor EFA solution to the 49 items that started the item "
         f"reduction phase: the {len(cross) + len(miss_ex)} excluded items and the items retained after the missing-data review, "
         f"with the rule applied. $\\lambda$: primary loading; 2nd $\\lambda$: second-highest loading and its factor "
         f"(three-factor solution, collapsed ratings). Missing \\%: overall and highest in one system.}}",
         "\\label{tab:screening-decisions}",
         "\\begin{tabular}{l>{\\raggedright\\arraybackslash}p{5.0cm}lcc>{\\raggedright\\arraybackslash}p{2.1cm}>{\\raggedright\\arraybackslash}p{3.9cm}}",
         "\\hline", head, "\\hline",
         f"\\multicolumn{{7}}{{l}}{{\\textit{{Excluded: cross-loading (2nd $\\lambda > {CROSS_CUT:.2f}$), {len(cross)} items}}}} \\\\"]
    T += [row(c, "cross-loading") for c in cross.index]
    T += ["\\hline",
          f"\\multicolumn{{7}}{{l}}{{\\textit{{Excluded in the missing-data review, {len(miss_ex)} items}}}} \\\\"]
    T += [row(c, missing_rule(c)) for c in miss_ex.index]
    T += ["\\hline",
          f"\\multicolumn{{7}}{{l}}{{\\textit{{Retained after the missing-data review, {len(kept)} items}}}} \\\\"]
    T += [row(c, missing_rule(c)) for c in kept.index]
    T += ["\\hline", "\\end{tabular}", "\\par\\smallskip",
          "{\\footnotesize\\raggedright Missing-data review: items with more than "
          f"{SYSTEM_MAX:g}\\% missing answers in at least one system were excluded when they also had (1) a primary loading "
          f"below {WEAK:.2f}, (2) redundancy with another item, or (3) content tied to a feature available only in some tools "
          "or to a particular kind of data, so that missing answers probably reflect non-applicability. "
          "Task = Task\\_cognition, Sys = System, Vis = Visualization.\\par}",
          "\\end{table*}"]
    (STEP / "output" / "table-screening-decisions.tex").write_text("\n".join(T) + "\n", encoding="utf-8")
    print(f"Wrote table-screening-decisions.tex: {len(cross)} cross-loading, {len(miss_ex)} missing-data, {len(kept)} retained")


if __name__ == "__main__":
    main()
